import type { RoleAchievementDefinition, RoleId } from "./v2-types";

// Display-only role rosters. No condition evaluation, rewards settlement or statistics IO.
export interface PreviewAchievement extends RoleAchievementDefinition {
  designCode: string;
  difficulty: string;
  requiredRoleId: RoleId;
  previewOnly: true;
}

type AchievementDraftRow = readonly [code: string, icon: string, title: string, difficulty: string, description: string];

function defineAchievements(roleId: RoleId, rows: readonly AchievementDraftRow[]): PreviewAchievement[] {
  return rows.map(([designCode, icon, title, difficulty, description]) => ({
    id: `${roleId}:${designCode.toLowerCase()}`, icon, title, description,
    rewardText: "", designCode, difficulty, requiredRoleId: roleId, previewOnly: true,
  }));
}

