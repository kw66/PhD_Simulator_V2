for (const fileName of files) {
  const filePath = path.join(desktopRoot, fileName);
  const html = fs.readFileSync(filePath, "utf8");
  const pattern = /(<script type="application\/json" id="report-data">)([\s\S]*?)(<\/script>)/u;
  const match = pattern.exec(html);
  if (!match) throw new Error(`${fileName}: report-data not found`);
  const data = JSON.parse(match[2]);

  data.introSource = replaceAllKnown(data.introSource);
  data.factsSource = replaceAllKnown(data.factsSource);
  for (const group of data.eventGroups) {
    group.name = replaceAllKnown(group.name);
    group.category = replaceAllKnown(group.category);
    group.trigger = replaceAllKnown(group.trigger);
    group.key = replaceAllKnown(group.key);
    for (const variant of group.variants) {
      variant.name = replaceAllKnown(variant.name);
      variant.content = replaceAllKnown(variant.content);
    }
  }
  for (const group of data.eventGroups) {
    syncResolvedEventRules(group, data.mode);
    syncResearchChoreSan(group, data.mode);
  }
  syncRuntimeEventMetadata(data);

  const peerReview = data.eventGroups.find((group) => group.name === "帮忙审稿");
  if (!peerReview) throw new Error(`${fileName}: peer review group not found`);
  syncPeerReview(peerReview, data.mode);

  const scholarship = data.eventGroups.find((group) => group.name === "国奖评选");
  if (!scholarship) throw new Error(`${fileName}: scholarship group not found`);
  scholarship.trigger = "第 2 月（10 月），第 2 年及以后；玩家可申报或继续积累成果";
  scholarship.variants = [{ name: "累计申报与隐藏分数线", content: scholarshipContent(data.mode) }];

  const phdDecision = data.eventGroups.find((group) => group.name === "转博抉择");
  if (!phdDecision) throw new Error(`${fileName}: PhD decision group not found`);
  if (data.mode === "copy") {
    syncPhdDecisionCopy(phdDecision);
    for (const group of data.eventGroups) syncZeroProgressCopy(group);
  }

  const serialized = JSON.stringify(data).replaceAll("</script", "<\\/script");
  const nextHtml = html.replace(pattern, `$1${serialized}$3`);
  fs.writeFileSync(filePath, nextHtml, "utf8");
}

