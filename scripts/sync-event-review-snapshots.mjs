function replaceFirstChoiceNarrative(content, choiceLabel, lines) {
  const choiceIndex = content.indexOf(`1. ${choiceLabel}`);
  if (choiceIndex < 0) return content;
  const markerIndex = content.indexOf("具体文案：", choiceIndex);
  if (markerIndex < 0) return content;
  const narrativeStart = content.indexOf("\n", markerIndex) + 1;
  const optionsIndex = content.indexOf("\n    选项：", narrativeStart);
  if (narrativeStart <= 0 || optionsIndex < 0) return content;
  const narrative = lines.map((line) => `      ${line}`).join("\n      \n");
  return `${content.slice(0, narrativeStart)}${narrative}${content.slice(optionsIndex)}`;
}

